/** Is this pin inside the country's delivery region? (ray casting) */
export function isInServiceArea(country: CountryCode, lat: number, lng: number): boolean {
  const ring = SERVICE_AREAS[country].ring;
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i];
    const [xj, yj] = ring[j];
    if (yi > lat !== yj > lat && lng < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}
